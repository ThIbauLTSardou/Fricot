export function searchLocalRecipes(query: string): LocalRecipe[] {
  if (!query.trim()) return [];
  const q = query
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");

  return LOCAL_RECIPES.filter((recipe) => {
    const name = recipe.name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "");
    const ingredientNames = recipe.ingredients
      .map((ing) =>
        ing.name
          .toLowerCase()
          .normalize("NFD")
          .replace(/[̀-ͯ]/g, "")
      )
      .join(" ");
    return name.includes(q) || ingredientNames.includes(q);
  });
}
